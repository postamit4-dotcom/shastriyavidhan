function hasRequiredGrahaDoshHubFields(service) {
  const hub = service.grahaDoshHub;
  if (!hub) return false;

  return grahaDoshPublicFields.every((field) => {
    const value = hub[field];
    if (Array.isArray(value)) return value.length > 0;
    if (value && typeof value === "object") return Object.keys(value).length > 0;
    return Boolean(value);
  });
}

export function getGrahaDoshShantiServices() {
  return servicesForCategorySlug(grahaDoshShantiHub.categorySlug).filter(
    (service) => isActiveIndexableService(service) && hasRequiredGrahaDoshHubFields(service),
  );
}

export function grahaDoshShantiCatalogueIssues() {
  const issues = [];
  const linkedServices = servicesForCategorySlug(grahaDoshShantiHub.categorySlug);
  const activeServices = getGrahaDoshShantiServices();

  if (activeServices.length === 0) {
    issues.push("No active, indexable Graha & Dosh Shanti services have complete hub fields.");
  }

  for (const service of linkedServices) {
    if (!service.grahaDoshHub) {
      issues.push(`${service.slug} is linked to the category but lacks grahaDoshHub fields.`);
    } else if (isActiveIndexableService(service) && !hasRequiredGrahaDoshHubFields(service)) {
      issues.push(`${service.slug} has incomplete grahaDoshHub fields.`);
    }
  }

  if (!grahaDoshShantiHub.review.catalogueOwner) {
    issues.push("Missing Graha & Dosh Shanti catalogue owner.");
  }

  if (!grahaDoshShantiHub.review.religiousReviewer) {
    issues.push("Missing named religious reviewer for Graha & Dosh Shanti taxonomy.");
  }

  if (!grahaDoshShantiHub.review.reviewedAt) {
    issues.push("Missing last-reviewed date for Graha & Dosh Shanti catalogue.");
  }

  return issues;
}

